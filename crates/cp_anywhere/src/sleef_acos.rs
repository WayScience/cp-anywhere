use std::f64::consts::{FRAC_PI_2, PI};

const COEFFICIENTS: [f64; 12] = [
    0.166_666_666_666_649_75,
    0.075_000_000_003_785_82,
    0.044_642_856_813_771_024,
    0.030_381_959_280_381_322,
    0.022_371_761_819_320_483,
    0.017_359_569_912_236_146,
    0.013_887_151_845_016_092,
    0.012_153_605_255_773_773,
    0.006_606_077_476_277_171,
    0.019_290_454_772_679_107,
    -0.015_819_182_433_299_966,
    0.031_615_876_506_539_346,
];

pub(crate) fn acos(value: f64) -> f64 {
    let magnitude = value.abs();
    let small = magnitude < 0.5;
    let z = if small {
        value * value
    } else {
        (1.0 - magnitude) * 0.5
    };
    let x = if small { magnitude } else { z.sqrt() };

    // SLEEF's POLY12 evaluates three groups of four coefficients by Estrin's
    // method. Keep multiply and add separate, as in its scalar purec build.
    let z2 = z * z;
    let z4 = z2 * z2;
    let z8 = z4 * z4;
    let quartets = std::array::from_fn::<_, 3, _>(|i| {
        let j = i * 4;
        let low = z * COEFFICIENTS[j + 1] + COEFFICIENTS[j];
        let high = z * COEFFICIENTS[j + 3] + COEFFICIENTS[j + 2];
        z2 * high + low
    });
    let poly = z8 * quartets[2] + (z4 * quartets[1] + quartets[0]);
    let correction = poly * (z * x);
    if small {
        FRAC_PI_2 - (x.copysign(value) + correction.copysign(value))
    } else {
        let angle = (x + correction) * 2.0;
        if value < 0.0 {
            // The upstream routine returns only the high component of the
            // double-double subtraction, which is the rounded PI - angle.
            PI - angle
        } else {
            angle
        }
    }
}

#[cfg(test)]
mod tests {
    use super::acos;

    #[test]
    fn matches_sleef_purec_at_endpoints_and_branch_boundary() {
        // Output bits captured from the pinned upstream Sleef_acosd1_u35purec.
        let cases = [
            (-1.0, 0x4009_21fb_5444_2d18),
            (-0.999_999_999_999_999_9, 0x4009_21fb_5244_2d18),
            (-0.9, 0x4005_8647_6251_e745),
            (-0.500_000_000_000_000_1, 0x4000_c152_382d_7366),
            (-0.5, 0x4000_c152_382d_7366),
            (-0.499_999_999_999_999_94, 0x4000_c152_382d_7365),
            (-0.0, 0x3ff9_21fb_5444_2d18),
            (0.0, 0x3ff9_21fb_5444_2d18),
            (0.01, 0x3ff8_f905_64f7_0dfa),
            (0.499_999_999_999_999_94, 0x3ff0_c152_382d_7366),
            (0.5, 0x3ff0_c152_382d_7365),
            (0.500_000_000_000_000_1, 0x3ff0_c152_382d_7365),
            (0.9, 0x3fdc_dd9f_8f92_2e98),
            (0.999_999_999_999_999_9, 0x3e50_0000_0000_0000),
            (1.0, 0),
        ];
        for (input, expected) in cases {
            assert_eq!(acos(input).to_bits(), expected, "acos({input})");
        }
    }

    #[test]
    fn returns_nan_outside_the_domain() {
        for input in [-1.1, 1.1, f64::NEG_INFINITY, f64::INFINITY, f64::NAN] {
            assert!(acos(input).is_nan());
        }
    }
}

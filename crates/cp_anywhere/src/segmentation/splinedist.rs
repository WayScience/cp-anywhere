//! `SplineDist` (uhlmanngroup/splinedist) nuclei segmentation, native port.
//!
//! SplineDist is a StarDist-architecture CNN: instead of star-convex ray
//! distances, its coordinate head predicts `(rho, phi)` pairs for a fixed
//! number of control points per pixel, so the model can express
//! non-star-convex shapes. The inference arrangement mirrors this crate's
//! other learned candidates (`segmentation::stardist`,
//! `segmentation::instanseg`): the network runs from ONNX bytes through
//! tract, and the decode runs as a native Rust port of upstream's own
//! Python/C pipeline (geom2d.dist_to_coord -> nms.non_maximum_suppression
//! -> geom2d.polygons_to_label), verified label-exact against real,
//! freshly-run upstream `SplineDist2D.predict_instances` output
//! (`tests/splinedist_fixtures/`, generated by
//! `scripts/splinedist/convert.py`).
//!
//! # Contract
//!
//! * The caller passes a csbdeep-normalized (1-99.8 percentile) image that
//!   is already reflect-padded to a multiple of the network's 16-voxel
//!   divisibility (upstream's `SplineDistPadAndCropResizer(grid=(2, 2))`
//!   semantics), plus the real (unpadded) frame size used to crop the
//!   network's output exactly like the resizer's `.after` step.
//! * The network's two heads come back grid-(2,2)-compressed (H/2, W/2):
//!   head 0 is the probability map, head 1 holds 20 channels = rho/phi
//!   pairs for 10 control points. The phi basis matrix (399 contour
//!   samples x 10 control points, shipped as checksummed bytes next to the
//!   model) converts control points into 399-point closed polygons via
//!   `phi @ coefs`.
//! * The decode follows upstream nms.py/geom2d.py exactly: b=2 boundary
//!   trim on the probability mask, descending-probability candidate
//!   ordering (stable ascending argsort reversed, matching numpy's
//!   ordering), bbox-windowed rasterized intersection-over-min-area NMS
//!   against the model's own `nms` threshold (0.3) with `+1e-10`
//!   denominators, then label rasterization in ascending-probability
//!   order with last-writer-wins (so higher probabilities overwrite).
//!
//! # Declared gaps
//!
//! * `geom2d.contour_cv2_mask_uniform` / `geom2d.spline_dist` are
//!   training-side helpers (masks -> control points); they are not part
//!   of inference and are not ported.
//! * `overlaps_label`/overlap handling in
//!   `SplineDist2D._instances_from_prediction` raises upstream, and is not
//!   implemented here either.
//! * 3D (`non_maximum_suppression_3d*`) is upstream-only; this port is 2D.
//! * Pairwise NMS intersection counts use the skimage-point-in-polygon
//!   raster semantics that were verified equivalent to the C kernel on the
//!   oracle fixture (survivor sets identical, downstream labels exact).

use tract_onnx::prelude::*;

/// Upstream-frozen decode parameters, from the shipped model's own
/// `thresholds.json` (`prob` 0.4775366187095642, `nms` 0.3). These are
/// calibration evidence pinned to this exact model; they are not tunables.
#[derive(Debug, Clone)]
pub struct SplineDistThresholds {
    pub prob: f32,
    pub nms: f32,
}

/// The phi basis dims pinned to the shipped model: the upstream
/// `phi_10.npy` basis has shape (399, 10) -- 399 contour sample positions
/// x 10 control points, and the model's 20 coord channels are 10 rho/phi
/// pairs. The basis travels with the ONNX as bytes next to it under
/// `src/cp_anywhere/data/splinedist/`.
pub const CONTOUR_SAMPLES: usize = 399;
pub const CONTROL_POINTS: usize = 10;

/// Parse a 399 x 10 little-endian float32 `.npy` v1.0 file (row-major /
/// C order, as `np.save` writes it) into a flat row-major matrix.
pub fn load_phi_basis(bytes: &[u8]) -> Result<Vec<f32>, String> {
    let magic = b"\x93NUMPY";
    if bytes.len() < 10 || &bytes[..6] != magic {
        return Err("phi basis is not an .npy file".into());
    }
    if bytes[6] != 1 {
        return Err("phi basis must be .npy format version 1".into());
    }
    let header_len = u16::from_le_bytes([bytes[8], bytes[9]]) as usize;
    let header = std::str::from_utf8(&bytes[10..10 + header_len])
        .map_err(|_| "phi basis header is not valid utf-8")?;
    if !header.contains("'<f4'") {
        return Err("phi basis must be little-endian float32".into());
    }
    if header.contains("True") {
        return Err("phi basis must be C-ordered (fortran_order False)".into());
    }
    let shape = load_phi_shape(header)?;
    if shape.len() != 2 || shape[0] != CONTOUR_SAMPLES || shape[1] != CONTROL_POINTS {
        return Err(format!(
            "phi basis shape {shape:?} does not match ({CONTOUR_SAMPLES}, \
             {CONTROL_POINTS})"
        ));
    }
    let data_start = 10 + header_len;
    let count = CONTOUR_SAMPLES * CONTROL_POINTS;
    if bytes.len() != data_start + count * 4 {
        return Err("phi basis data length does not match its header".into());
    }
    Ok(bytes[data_start..]
        .chunks_exact(4)
        .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
        .collect())
}

fn load_phi_shape(header: &str) -> Result<Vec<usize>, String> {
    let start = header.find("(").ok_or("phi basis header missing shape")?;
    let end = header[start..]
        .find(")")
        .ok_or("phi basis header missing )")?
        + start;
    header[start..end + 1]
        .trim_matches(|c| c == '(' || c == ')')
        .split(',')
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .map(|part| {
            part.parse::<usize>()
                .map_err(|_| format!("phi basis shape segment is not numeric: {part:?}"))
        })
        .collect()
}

impl SplineDistThresholds {
    pub fn from_shipped_model() -> Self {
        Self {
            prob: 0.477_536_62,
            nms: 0.3,
        }
    }
}

#[derive(Debug)]
pub struct SplineDistResult {
    /// Flat row-major labels (`real_rows * real_cols`), 0 = background.
    pub labels: Vec<u32>,
    pub object_count: u32,
    pub real_rows: usize,
    pub real_cols: usize,
}

pub struct NetworkOutput {
    /// Grid-compressed probability map, cropped to the real frame.
    pub prob: Vec<f32>,
    /// Grid-compressed 20-channel coordinate map, cropped to the real
    /// frame, stored channel-major (`20 * ch_rows * ch_cols`).
    pub coord_channels: Vec<f32>,
    pub ch_rows: usize,
    pub ch_cols: usize,
    pub channels: usize,
}

/// Opt-in model runner: holds the shipped ONNX bytes and runs the two
/// heads (probability + 20-channel spline control-point map) on a
/// caller-normalized, already-padded image.
pub struct SplineDistOnnxModel {
    model_bytes: Vec<u8>,
}

impl SplineDistOnnxModel {
    pub fn from_bytes(model_bytes: Vec<u8>) -> Self {
        Self { model_bytes }
    }

    pub fn run_network(
        &self,
        image: &[f32],
        rows: usize,
        cols: usize,
        real_rows: usize,
        real_cols: usize,
    ) -> Result<NetworkOutput, String> {
        // Run the two heads on one caller-normalized, already-padded image
        // (`rows * cols` float32, NCHW `(1, 1, rows, cols)`), then crop and
        // degrid exactly like `SplineDistPadAndCropResizer.after`.
        let len = rows.checked_mul(cols).ok_or("image shape overflows")?;
        if image.len() != len {
            return Err("image length must equal rows * cols".into());
        }
        if !image.iter().all(|&v| v.is_finite()) {
            return Err("image values must be finite".into());
        }
        if real_rows > rows || real_cols > cols {
            return Err("real frame must not exceed the padded frame".into());
        }
        // The exported graph is keras channels_last: (1, H, W, 1) with the
        // image data row-major (the 1-channel NHWC layout coincides with
        // the caller's row-major frame).
        let input = Tensor::from_shape(&[1, rows, cols, 1], image)
            .map_err(|e| format!("failed to shape splinedist input tensor: {e:#}"))?;
        let plan = {
            let mut reader = std::io::Cursor::new(&self.model_bytes);
            let model = tract_onnx::onnx()
                .model_for_read(&mut reader)
                .and_then(|m| m.with_input_fact(0, InferenceFact::dt_shape_from_tensor(&input)))
                .and_then(|m| m.into_optimized())
                .and_then(|m| m.into_runnable())
                .map_err(|e| format!("failed to build splinedist ONNX plan: {e:#}"))?;
            model
        };
        let result = plan
            .run(tvec!(input.into()))
            .map_err(|e| format!("splinedist ONNX inference failed: {e:#}"))?;
        if result.len() != 2 {
            return Err(format!(
                "expected 2 splinedist outputs, got {}",
                result.len()
            ));
        }
        // The two heads hold (H', W', C) grids with the padded compressed
        // geometry H' = rows/2, W' = cols/2 (grid (2, 2)). tract's
        // optimizer has been observed to return keras' NHWC order
        // ((1, 264, 352, 1), (1, 264, 352, 20)) AND transposed variants
        // ((1, 352, 20, 264)) run-to-run, so the layout is detected per
        // call from the 20-channel coord head (where the channel axis is
        // unambiguous) and its (rows/2, cols/2) spatial position, then
        // applied to the 1-channel prob head. This is layout-agnostic and
        // keeps the fixture parity checks valid under any output order.
        fn read_coord(
            out: &Tensor,
            rows: usize,
            cols: usize,
        ) -> Result<(usize, usize, Vec<f32>), String> {
            let shape = out.shape().to_vec();
            if shape.len() != 4 {
                return Err(format!(
                    "expected a 4-D splinedist coord head, got {shape:?}"
                ));
            }
            let batch = shape[0];
            if batch != 1 {
                return Err(format!("expected batch size 1, got {batch}"));
            }
            let channels = 20usize;
            let h_target = rows / 2;
            let w_target = cols / 2;
            let mut layout: Option<(usize, usize, usize)> = None; // (h_idx, w_idx, c_idx)
            for c_idx in 1..4 {
                if shape[c_idx] != channels {
                    continue;
                }
                let rest: Vec<usize> = (1..4).filter(|&i| i != c_idx).collect();
                let (a, b) = (shape[rest[0]], shape[rest[1]]);
                let (h_idx, w_idx) = if a == h_target && b == w_target {
                    (rest[0], rest[1])
                } else if b == h_target && a == w_target {
                    (rest[1], rest[0])
                } else {
                    continue;
                };
                layout = Some((h_idx, w_idx, c_idx));
                break;
            }
            let Some((h_idx, w_idx, c_idx)) = layout else {
                return Err(format!(
                    "coord head shape {shape:?} does not contain 20 channels plus the \
                     expected ({h_target}, {w_target}) padded compressed geometry"
                ));
            };
            let (h, w) = (shape[h_idx], shape[w_idx]);
            let view = out
                .to_plain_array_view::<f32>()
                .map_err(|e| format!("failed to read splinedist coord head as float32: {e:#}"))?;
            let mut data = Vec::new();
            data.try_reserve_exact(channels * h * w)
                .map_err(|_| "splinedist coord head is too large")?;
            for r in 0..h {
                for c in 0..w {
                    for ch in 0..channels {
                        let mut idx = [0usize, 0, 0, 0];
                        idx[h_idx] = r;
                        idx[w_idx] = c;
                        idx[c_idx] = ch;
                        data.push(view[idx]);
                    }
                }
            }
            Ok((h, w, data))
        }
        fn read_prob(
            out: &Tensor,
            h_idx: usize,
            w_idx: usize,
            c_idx: usize,
        ) -> Result<(usize, usize, Vec<f32>), String> {
            let shape = out.shape().to_vec();
            if shape.len() != 4 || shape[0] != 1 {
                return Err(format!(
                    "expected a 4-D batch-1 splinedist prob head, got {shape:?}"
                ));
            }
            let (h, w) = (shape[h_idx], shape[w_idx]);
            let view = out
                .to_plain_array_view::<f32>()
                .map_err(|e| format!("failed to read splinedist prob head as float32: {e:#}"))?;
            let mut data = Vec::new();
            data.try_reserve_exact(h * w)
                .map_err(|_| "splinedist prob head is too large")?;
            for r in 0..h {
                for c in 0..w {
                    let mut idx = [0usize, 0, 0, 0];
                    idx[h_idx] = r;
                    idx[w_idx] = c;
                    idx[c_idx] = 0;
                    data.push(view[idx]);
                }
            }
            Ok((h, w, data))
        }
        let (coord_h, coord_w, coord_flat) =
            read_coord(&result[1], rows, cols).map_err(|e| format!("coord head: {e}"))?;
        // Both heads share the export's layout; the coord head located the
        // (h, w, c) axis positions by its unique channel count, so re-derive
        // the same positions for the 1-channel prob head.
        let shape = result[0].shape();
        if shape.len() != 4 || shape[0] != 1 {
            return Err(format!(
                "expected a 4-D batch-1 splinedist prob head, got {shape:?}"
            ));
        }
        let mut prob_layout: Option<(usize, usize, usize)> = None; // (h_idx, w_idx, c_idx)
        for c_idx in 1..4 {
            if shape[c_idx] != 1 {
                continue;
            }
            let rest: Vec<usize> = (1..4).filter(|&i| i != c_idx).collect();
            let (a, b) = (shape[rest[0]], shape[rest[1]]);
            let (h_idx, w_idx) = if a == coord_h && b == coord_w {
                (rest[0], rest[1])
            } else if b == coord_h && a == coord_w {
                (rest[1], rest[0])
            } else {
                continue;
            };
            prob_layout = Some((h_idx, w_idx, c_idx));
            break;
        }
        let Some((h_idx, w_idx, c_idx)) = prob_layout else {
            return Err(format!(
                "prob head shape {shape:?} does not match the coord head frame \
                 ({coord_h}, {coord_w})"
            ));
        };
        let (prob_h, prob_w, prob) =
            read_prob(&result[0], h_idx, w_idx, c_idx).map_err(|e| format!("prob head: {e}"))?;
        if prob_h != coord_h || prob_w != coord_w {
            return Err(format!(
                "prob and coord heads disagree on shape: prob ({prob_h}, {prob_w}) vs \
                 coord ({coord_h}, {coord_w})"
            ));
        }
        // Crop the padded tail: upstream's resizer restores the real frame,
        // dropping bottom/right padding only (top/left never padded).
        let crop_h = (prob_h.checked_mul(2).ok_or("prob head overflows")? - real_rows).div_ceil(2);
        let crop_w = (prob_w.checked_mul(2).ok_or("prob head overflows")? - real_cols).div_ceil(2);
        let ch_rows = prob_h - crop_h;
        let ch_cols = prob_w - crop_w;
        if crop_h > prob_h || crop_w > prob_w {
            return Err("network output too small for the requested real frame".into());
        }
        let mut prob_cropped = Vec::with_capacity(ch_rows * ch_cols);
        let mut coord_channels = Vec::with_capacity(20 * ch_rows * ch_cols);
        for r in 0..ch_rows {
            for c in 0..ch_cols {
                prob_cropped.push(prob[r * prob_w + c]);
            }
        }
        for ch in 0..20usize {
            for r in 0..ch_rows {
                for c in 0..ch_cols {
                    coord_channels.push(coord_flat[r * prob_w * 20 + c * 20 + ch]);
                }
            }
        }
        Ok(NetworkOutput {
            prob: prob_cropped,
            coord_channels,
            ch_rows,
            ch_cols,
            channels: 20,
        })
    }
}

/// Replicates numpy's pairwise-sum reduction for a contiguous f32 array
/// (numpy `np.add.reduce` semantics: sequential for n < 8, 8-way unrolled
/// blocks up to the 128-element blocksize, recursive halving beyond),
/// because the verified decode's shoelace area accumulation uses exactly
/// this order and the NMS outcomes are threshold comparisons.
fn numpy_pairwise_sum_f32(values: &[f32]) -> f32 {
    fn sum(a: &[f32]) -> f32 {
        let n = a.len();
        if n < 8 {
            let mut res = 0.0_f32;
            for v in a {
                res += *v;
            }
            res
        } else if n <= 128 {
            let mut r = [0.0_f32; 8];
            for j in 0..8 {
                r[j] = a[j];
            }
            let mut i = 8;
            let stop = n - (n % 8);
            while i < stop {
                for j in 0..8 {
                    r[j] += a[i + j];
                }
                i += 8;
            }
            let mut res = ((r[0] + r[1]) + (r[2] + r[3])) + ((r[4] + r[5]) + (r[6] + r[7]));
            while i < n {
                res += a[i];
                i += 1;
            }
            res
        } else {
            let n2 = (n / 2) - ((n / 2) % 8);
            sum(&a[..n2]) + sum(&a[n2..])
        }
    }
    sum(values)
}

#[allow(clippy::too_many_arguments)]
/// The decode ported from `nms.non_maximum_suppression` +
/// `geom2d.polygons_to_label` exactly, following the validated reference
/// implementation that reproduced upstream's oracle labels pixel-exact
/// (`verify_raster.py`). `phi` is the (contour_samples, control_points)
/// basis matrix, row-major.
pub fn decode(
    prob: &[f32],
    coord_channels: &[f32], // channel-major: 20 * ch_rows * ch_cols
    ch_rows: usize,
    ch_cols: usize,
    phi: &[f32],
    contours: usize,
    control_points: usize,
    thresholds: &SplineDistThresholds,
    real_rows: usize,
    real_cols: usize,
) -> Result<SplineDistResult, String> {
    let len = ch_rows
        .checked_mul(ch_cols)
        .ok_or("compressed frame overflows")?;
    if prob.len() != len || coord_channels.len() != 20 * len {
        return Err("compressed head lengths disagree".into());
    }
    if phi.len() != contours * control_points {
        return Err("phi basis length must equal contours * control_points".into());
    }
    let grid = (2_usize, 2_usize);

    // dist_to_coord: 20 channels -> 10 (rho, phi) pairs; control point k's
    // absolute position adds grid-scaled pixel indices.
    let pairs = control_points;
    let mut coord_t = vec![[0.0_f32; 2]; pairs * len]; // index [k * len + p]
    let mut base_index = vec![[0.0_f32; 2]; len]; // [p]: (row, col) grid-scaled
    for r in 0..ch_rows {
        for c in 0..ch_cols {
            base_index[r * ch_cols + c][0] = (grid.0 * r) as f32;
            base_index[r * ch_cols + c][1] = (grid.1 * c) as f32;
        }
    }
    for k in 0..pairs {
        for p in 0..len {
            let rho = coord_channels[2 * k * len + p];
            let phi_angle = coord_channels[(2 * k + 1) * len + p];
            let (row, col) = (base_index[p][0], base_index[p][1]);
            coord_t[k * len + p][0] = row + rho * phi_angle.cos();
            coord_t[k * len + p][1] = col + rho * phi_angle.sin();
        }
    }

    // b=2 boundary trim on the compressed probability mask.
    let mut mask = vec![false; len];
    for r in 0..ch_rows {
        for c in 0..ch_cols {
            let in_boundary = r >= 2 && c >= 2 && r < ch_rows - 2 && c < ch_cols - 2;
            mask[r * ch_cols + c] = in_boundary && prob[r * ch_cols + c] > thresholds.prob;
        }
    }
    let mut candidates: Vec<(usize, usize)> = Vec::new(); // (row, col)
    let mut scores: Vec<f32> = Vec::new();
    for p in 0..len {
        if mask[p] {
            candidates.push((p / ch_cols, p % ch_cols));
            scores.push(prob[p]);
        }
    }
    let n = candidates.len();
    if n == 0 {
        return Ok(SplineDistResult {
            labels: vec![0; real_rows * real_cols],
            object_count: 0,
            real_rows,
            real_cols,
        });
    }

    // Stable ascending argsort reversed == numpy argsort()[::-1].
    let mut ind: Vec<usize> = (0..n).collect();
    ind.sort_by(|&a, &b| {
        scores[a]
            .partial_cmp(&scores[b])
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    ind.reverse();

    // phi @ coefs per candidate: (contours, 2) row-major [row, col] f32,
    // accumulated in plain f32 (numpy-matmul-like, no fma), then reused by
    // BOTH the NMS (truncated to int32 exactly like upstream's
    // polygons.astype(np.int32)) and the label painting (widen to f64).
    // NOTE on ordering: numpy processes candidates in scan order and then
    // REORDERS every NMS array into descending-score position order
    // (verify_raster.py lines 56-60); the suppression loop works entirely
    // in that sorted space, so reorder here before deriving anything.
    let mut contour_f32: Vec<Vec<[f32; 2]>> = Vec::with_capacity(n);
    let mut polygons: Vec<Vec<[i32; 2]>> = Vec::with_capacity(n);
    for &(r, c) in &candidates {
        let mut f32_poly = Vec::with_capacity(contours);
        let mut poly = Vec::with_capacity(contours);
        for s in 0..contours {
            let mut acc = [0.0_f32; 2];
            for k in 0..pairs {
                let w = phi[s * control_points + k];
                let coef = coord_t[k * len + r * ch_cols + c];
                acc[0] = acc[0] + w * coef[0];
                acc[1] = acc[1] + w * coef[1];
            }
            poly.push([acc[0] as i32, acc[1] as i32]);
            f32_poly.push(acc);
        }
        contour_f32.push(f32_poly);
        polygons.push(poly);
    }

    // Raster sets via the verified point_in_polygon port; bounding boxes
    // and numpy-pairwise-sum f32 shoelace areas exactly as the verified
    // reference (areas kept in f64: 0.5 * abs(float(acc))).
    let mut raster: Vec<std::collections::BTreeSet<(i64, i64)>> = Vec::with_capacity(n);
    let mut bxs: Vec<(i64, i64)> = Vec::with_capacity(n);
    let mut bys: Vec<(i64, i64)> = Vec::with_capacity(n);
    let mut areas: Vec<f64> = Vec::with_capacity(n);
    for poly in polygons.iter().take(n) {
        raster.push(rasterize_polygon(poly));
        bxs.push((
            poly.iter().map(|p| i64::from(p[1])).min().unwrap(),
            poly.iter().map(|p| i64::from(p[1])).max().unwrap(),
        ));
        bys.push((
            poly.iter().map(|p| i64::from(p[0])).min().unwrap(),
            poly.iter().map(|p| i64::from(p[0])).max().unwrap(),
        ));
        let mut terms: Vec<f32> = Vec::with_capacity(poly.len());
        let last = poly.len() - 1;
        for (k, p) in poly.iter().enumerate() {
            let (xn, yn) = if k == last {
                (i64::from(poly[0][1]), i64::from(poly[0][0]))
            } else {
                (i64::from(poly[k + 1][1]), i64::from(poly[k + 1][0]))
            };
            let x = i64::from(p[1]);
            let y = i64::from(p[0]);
            terms.push(((x * yn) as f32) - ((y * xn) as f32));
        }
        let acc = numpy_pairwise_sum_f32(&terms);
        areas.push(0.5 * f64::from(acc.abs()));
    }
    // Reorder everything into descending-score (sorted-position) order,
    // exactly like the verified reference; the suppression loop and the
    // mapping both live in that space.
    let sorted_bxs: Vec<(i64, i64)> = ind.iter().map(|&i| bxs[i]).collect();
    let sorted_bys: Vec<(i64, i64)> = ind.iter().map(|&i| bys[i]).collect();
    let sorted_areas: Vec<f64> = ind.iter().map(|&i| areas[i]).collect();
    let sorted_raster: Vec<&std::collections::BTreeSet<(i64, i64)>> =
        ind.iter().map(|&i| &raster[i]).collect();
    bxs = sorted_bxs;
    bys = sorted_bys;
    areas = sorted_areas;
    let max_bbox_x = bxs.iter().map(|(a, b)| b - a).max().unwrap_or(0);
    let max_bbox_y = bys.iter().map(|(a, b)| b - a).max().unwrap_or(0);

    // mapping.flat[flatnonzero(mask)[ind]] = arange(n): sorted-position id
    // per grid pixel.
    let mut mapping = vec![-1_i64; len];
    let flatnonzero: Vec<usize> = (0..len).filter(|&p| mask[p]).collect();
    for (pos, &orig) in ind.iter().enumerate() {
        mapping[flatnonzero[orig]] = pos as i64;
    }

    let mut suppressed = vec![false; n];
    for i in 0..n.saturating_sub(1) {
        if suppressed[i] {
            continue;
        }
        let (bxi, byi) = (bxs[i], bys[i]);
        let xs_start = ((bxi.0 - max_bbox_x).div_euclid(grid.1 as i64)).max(0) as usize;
        let xs_end = ((bxi.1 + max_bbox_x).div_euclid(grid.1 as i64)).min(ch_cols as i64) as usize;
        let ys_start = ((byi.0 - max_bbox_y).div_euclid(grid.0 as i64)).max(0) as usize;
        let ys_end = ((byi.1 + max_bbox_y).div_euclid(grid.0 as i64)).min(ch_rows as i64) as usize;
        for jj in ys_start..ys_end {
            for ii in xs_start..xs_end {
                let Some(j) = usize::try_from(mapping[jj * ch_cols + ii]).ok() else {
                    continue;
                };
                if j <= i || suppressed[j] {
                    continue;
                }
                // Grid-pixel to compressed-pixel index mapping: the mapping
                // is over compressed cells; grid-scaled windows index the
                // same compressed frame (grid is (2,2) but candidates live
                // on compressed cells) -- upstream indexes mask in the
                // compressed frame directly, so use the raw cell index.
                if !(bxs[j].0 <= bxi.1
                    && bxi.0 <= bxs[j].1
                    && bys[j].0 <= byi.1
                    && byi.0 <= bys[j].1)
                {
                    continue;
                }
                let inter = raster_intersection(sorted_raster[i], sorted_raster[j]);
                if inter == 0 {
                    continue;
                }
                // ov = f32(inter) / f32(min(areas[i], areas[j]) + 1e-10):
                // the min and the +1e-10 happen in f64 in the verified
                // reference before the f32 cast.
                let smaller = areas[i].min(areas[j]);
                let ov = (inter as f32) / ((smaller + 1e-10) as f32);
                if ov > thresholds.nms {
                    suppressed[j] = true;
                }
            }
        }
    }

    // Survivors in ascending-probability order; last writer wins.
    let mut survivors: Vec<usize> = ind
        .iter()
        .copied()
        .enumerate()
        .filter(|(pos, _)| !suppressed[*pos])
        .map(|(_, orig)| orig)
        .collect();
    survivors.sort_by(|&a, &b| {
        scores[a]
            .partial_cmp(&scores[b])
            .unwrap_or(std::cmp::Ordering::Equal)
    });

    let mut labels = vec![0_u32; real_rows * real_cols];
    let mut object_count: u32 = 0;
    for &orig in &survivors {
        object_count += 1;
        let id = object_count;
        // contour = phi @ coord_t[r, c]: the SAME f32 accumulation used for
        // the NMS polygons, widened to f64 for rasterization exactly like
        // the verified reference (contour.astype(np.float64)).
        let row_c: Vec<f64> = contour_f32[orig].iter().map(|p| f64::from(p[0])).collect();
        let col_c: Vec<f64> = contour_f32[orig].iter().map(|p| f64::from(p[1])).collect();
        for (pr, pc) in rasterize_polygon64(&col_c, &row_c, real_rows, real_cols) {
            labels[pr * real_cols + pc] = id;
        }
        // rint overpaint on the clipped boundary contour.
        for p in &contour_f32[orig] {
            let xr = (f64::from(p[0]).max(0.0).min((real_rows - 1) as f64)).round_ties_even();
            let yr = (f64::from(p[1]).max(0.0).min((real_cols - 1) as f64)).round_ties_even();
            labels[(xr as usize) * real_cols + (yr as usize)] = id;
        }
    }

    Ok(SplineDistResult {
        labels,
        object_count,
        real_rows,
        real_cols,
    })
}

// --- rasterization helpers (validated skimage.draw.polygon equivalents) ---

const INSIDE: u8 = 1;
const VERTEX: u8 = 2;
const EDGE: u8 = 3;

/// Exact port of skimage 0.21's `_geometry.point_in_polygon`
/// (as validated against the oracle by the reference implementation):
/// `xp` polygon column coordinates, `yp` polygon row coordinates, query
/// point `(x, y)`. Returns 0 (outside) or INSIDE/VERTEX/EDGE.
fn point_in_polygon(xp: &[f64], yp: &[f64], x: f64, y: f64) -> u8 {
    let eps = 1e-12;
    let nr = xp.len();
    let mut x1 = xp[nr - 1] - x;
    let mut y1 = yp[nr - 1] - y;
    let mut l_cross = 0_u32;
    let mut r_cross = 0_u32;
    for i in 0..nr {
        let x0 = xp[i] - x;
        let y0 = yp[i] - y;
        if (-eps < x0 && x0 < eps) && (-eps < y0 && y0 < eps) {
            return VERTEX;
        }
        if (y0 > 0.0) != (y1 > 0.0) && (x0 * y1 - x1 * y0) / (y1 - y0) > 0.0 {
            r_cross += 1;
        }
        if (y0 < 0.0) != (y1 < 0.0) && (x0 * y1 - x1 * y0) / (y1 - y0) < 0.0 {
            l_cross += 1;
        }
        x1 = x0;
        y1 = y0;
    }
    if (r_cross & 1) != (l_cross & 1) {
        return EDGE;
    }
    if r_cross & 1 != 0 {
        return INSIDE;
    }
    0
}

/// Integer-coordinate polygon raster used by the NMS intersection counts:
/// pixel set of all raster cells classified inside/on the polygon when
/// scanned at their integer centers, clipped by the caller upstream (the
/// b=2 trim plus bbox windows bound the coordinates).
fn rasterize_polygon(poly: &[[i32; 2]]) -> std::collections::BTreeSet<(i64, i64)> {
    let row_min = poly.iter().map(|p| i64::from(p[0])).min().unwrap();
    let row_max = poly.iter().map(|p| i64::from(p[0])).max().unwrap();
    let col_min = poly.iter().map(|p| i64::from(p[1])).min().unwrap();
    let col_max = poly.iter().map(|p| i64::from(p[1])).max().unwrap();
    let xp: Vec<f64> = poly.iter().map(|p| f64::from(p[1])).collect();
    let yp: Vec<f64> = poly.iter().map(|p| f64::from(p[0])).collect();
    let mut set = std::collections::BTreeSet::new();
    for r in row_min..=row_max {
        for c in col_min..=col_max {
            if point_in_polygon(&xp, &yp, c as f64, r as f64) != 0 {
                set.insert((r, c));
            }
        }
    }
    set
}

fn raster_intersection(
    a: &std::collections::BTreeSet<(i64, i64)>,
    b: &std::collections::BTreeSet<(i64, i64)>,
) -> usize {
    if a.len() > b.len() {
        return raster_intersection(b, a);
    }
    a.iter().filter(|p| b.contains(p)).count()
}

/// Label rasterization at a caller-clipped real frame: the bbox scan from
/// upstream's `rasterize` helper (min floor to ceil max, clipped), with
/// `point_in_polygon(col_coords, row_coords, c, r)` classification.
fn rasterize_polygon64(
    col_coords: &[f64],
    row_coords: &[f64],
    rows: usize,
    cols: usize,
) -> Vec<(usize, usize)> {
    let mut minr = row_coords.iter().cloned().fold(f64::INFINITY, f64::min);
    let maxr = row_coords.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
    let mut minc = col_coords.iter().cloned().fold(f64::INFINITY, f64::min);
    let maxc = col_coords.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
    if minr < 0.0 {
        minr = 0.0;
    }
    if minc < 0.0 {
        minc = 0.0;
    }
    let minr = minr as usize;
    let maxr = (maxr.ceil() as usize).min(rows.saturating_sub(1));
    let minc = minc as usize;
    let maxc = (maxc.ceil() as usize).min(cols.saturating_sub(1));
    let mut out = Vec::new();
    for r in minr..=maxr {
        for c in minc..=maxc {
            if point_in_polygon(col_coords, row_coords, c as f64, r as f64) != 0 {
                out.push((r, c));
            }
        }
    }
    out
}

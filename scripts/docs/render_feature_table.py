"""Render a human-readable supported-feature table to docs/features.md.

spec/features.yaml is the empirical CellProfiler 4.2.8 oracle inventory
from M1; its rust_status/wasm_status/cp_measure_status fields are
deliberately frozen placeholders ("not_started"/"unknown_m2") that
scripts/reference/generate.py always rewrites identically, because
tests/reference/test_reference.py::test_reference_replay_when_environment_is_configured
does a byte-for-byte replay comparison against it. Real implementation
status for downstream milestones belongs in the separate files each
milestone already produces -- spec/cp_measure-map.yaml (M2),
benchmarks/reports/native-parity.json (M3), benchmarks/reports/wasm-parity.json
(M4/M5) -- never in spec/features.yaml itself. This script only *reads*
those sources and writes a new file (docs/features.md); it never
modifies spec/features.yaml.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]

STATUS_RANK = {"fail": 0, "unknown": 1, "pass_tolerance": 2, "pass_exact": 3}


def aggregate_status(report_path: Path) -> dict[tuple[str, str], str]:
    rows = json.loads(report_path.read_text())["rows"]
    worst: dict[tuple[str, str], str] = defaultdict(lambda: "pass_exact")
    for row in rows:
        if row["object_scope"] == "relationship":
            continue
        key = (row["feature"], row["object_scope"])
        status = row["status"]
        if STATUS_RANK[status] < STATUS_RANK[worst[key]]:
            worst[key] = status
    return dict(worst)


def cp_measure_statuses(map_path: Path) -> dict[tuple[str, str], str]:
    data = yaml.safe_load(map_path.read_text())
    return {(f["name"], f["object_scope"]): f["status"] for f in data["features"]}


def main() -> None:
    inventory = yaml.safe_load((ROOT / "spec/features.yaml").read_text())
    native_status = aggregate_status(ROOT / "benchmarks/reports/native-parity.json")
    wasm_status = aggregate_status(ROOT / "benchmarks/reports/wasm-parity.json")
    cp_measure = cp_measure_statuses(ROOT / "spec/cp_measure-map.yaml")

    rows_for_table = []
    missing_measurements = []
    for feature in inventory["features"]:
        key = (feature["name"], feature["object_scope"])
        rust = native_status.get(key)
        wasm = wasm_status.get(key)
        mapped = cp_measure.get(key)
        if rust is None or wasm is None:
            missing_measurements.append(key)
        rows_for_table.append(
            {
                "module": feature["module"],
                "name": feature["name"],
                "object_scope": feature["object_scope"],
                "dimensionality": feature["dimensionality"],
                "rust_status": rust or "not_measured",
                "wasm_status": wasm or "not_measured",
                "cp_measure_status": mapped or feature["cp_measure_status"],
            }
        )

    if missing_measurements:
        msg = (
            f"{len(missing_measurements)} declared feature(s) have no native/wasm "
            f"parity measurement: {missing_measurements[:5]}..."
        )
        raise AssertionError(msg)

    rows_for_table.sort(key=lambda r: (r["module"], r["name"], r["object_scope"]))
    lines = [
        "# Supported feature table",
        "",
        "Generated by `scripts/docs/render_feature_table.py` by joining",
        "`spec/features.yaml` (the frozen empirical CellProfiler 4.2.8 oracle",
        "inventory, M1 -- never hand-edited or mutated by this script) with",
        "the real parity reports (`benchmarks/reports/native-parity.json`,",
        "`benchmarks/reports/wasm-parity.json`, M3-M5) and the cp_measure",
        "mapping (`spec/cp_measure-map.yaml`, M2). Regenerate after any",
        "parity re-run; do not hand-edit.",
        "",
        f"Total declared columns: {len(rows_for_table)} "
        "(see `spec/compatibility.md` for the full scope contract).",
        "",
        "| Module | Feature | Object scope | Dims | Rust | WASM | cp_measure |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows_for_table:
        dims = "/".join(str(d) for d in row["dimensionality"])
        lines.append(
            f"| {row['module']} | {row['name']} | {row['object_scope']} | "
            f"{dims} | {row['rust_status']} | {row['wasm_status']} | "
            f"{row['cp_measure_status']} |"
        )
    (ROOT / "docs/features.md").write_text("\n".join(lines) + "\n")
    print(
        json.dumps(
            {
                "table_rows": len(rows_for_table),
                "docs_features_md": str(ROOT / "docs/features.md"),
            }
        )
    )


if __name__ == "__main__":
    main()

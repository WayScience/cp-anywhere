"""Regression: the all-zero ("empty field") stress input.

The production pilot's stress-empty-field validation input
(A9-A9-p10-empty -- an all-zero 450x450 float DNA channel) diverged:
native declumping split the single all-foreground blob (global Otsu
threshold of a constant image is 0.0, so every pixel is foreground)
into 1555 spurious "nuclei", while the pinned real CellProfiler 4.2.8
oracle produces 0 objects. The oracle fixture
(``synthetic_declump_shape_propagate_empty_field``, generated by
``scripts/segmentation/generate_empty_field_fixture.py`` under the
pinned reference environment) pins the real labels; the generic
manifest replay in ``test_reference_alignment.py`` covers them too,
and this module adds the named, focused assertions plus the
primary->secondary chain (0 nuclei must yield 0 cells).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TypedDict

import numpy as np

import cp_anywhere

ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURE_DIR = ROOT / "fixtures/segmentation"
CASE_NAME = "synthetic_declump_shape_propagate_empty_field"


class PrimarySettings(TypedDict):
    threshold: str
    exclude_size: bool
    min_diameter: float
    max_diameter: float
    unclump_method: str
    watershed_method: str


PILOT_PRIMARY: PrimarySettings = {
    "threshold": "otsu",
    "exclude_size": True,
    "min_diameter": 10.0,
    "max_diameter": 40.0,
    "unclump_method": "shape",
    "watershed_method": "propagate",
}


def test_empty_field_matches_real_cellprofiler_oracle_exactly() -> None:
    case = json.loads((FIXTURE_DIR / f"{CASE_NAME}.json").read_text())
    assert case["object_count"] == 0
    assert case["threshold"] == 0.0

    pixels = np.load(FIXTURE_DIR / CASE_NAME / "pixels.npy")
    assert pixels.shape == (450, 450) and bool(np.all(pixels == 0))

    result = cp_anywhere.identify_primary_objects(pixels, **PILOT_PRIMARY)

    assert result.object_count == 0
    assert result.threshold == 0.0
    assert np.array_equal(
        result.labels, np.load(FIXTURE_DIR / CASE_NAME / "labels.npy")
    )
    # The one declumped field-sized object survives the small filter and
    # is erased by the max-size filter, matching the oracle.
    assert np.array_equal(
        result.small_removed_labels,
        np.load(FIXTURE_DIR / CASE_NAME / "small_removed_labels.npy"),
    )
    assert int(result.small_removed_labels.max()) == 1


def test_empty_field_yields_zero_secondary_objects() -> None:
    pixels = np.zeros((450, 450), dtype=np.float32)
    nuclei = cp_anywhere.identify_primary_objects(pixels, **PILOT_PRIMARY)
    assert nuclei.object_count == 0

    cells = cp_anywhere.identify_secondary_objects(
        np.zeros((450, 450), dtype=np.float32),
        nuclei.labels,
        primary_labels_in=nuclei.unedited_labels,
        method="propagation",
        regularization_factor=0.05,
        fill_holes=True,
    )
    assert int(np.asarray(cells.labels).max()) == 0
    assert bool(np.all(np.asarray(cells.labels) == 0))
